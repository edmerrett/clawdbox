/**
 * Write mod/hooks/sprites.ts: the thirteen animations from art/anims/*.json, packed for the
 * Claude Code mod (which has no filesystem of its own to read them from at run time).
 *
 *   npm run mod:sprites
 *
 * Each frame keeps its palette as 0xRRGGBB numbers and its 256 pixels as one string of
 * base-36 palette indices, so the file stays small and diffs stay readable.
 * test/mod.test.ts fails when the file is out of date with art/anims.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { AnimFile, PIXELS, STATES } from '../anim/types.js';

const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)));
export const MOD_SPRITES_PATH = join(ROOT, 'mod', 'hooks', 'sprites.ts');
export const ANIMS_DIR = join(ROOT, 'art', 'anims');

/** The source of mod/hooks/sprites.ts for the animations in `dir`. */
export function modSpritesSource(dir: string = ANIMS_DIR): string {
  const lines: string[] = [
    '// Generated by `npm run mod:sprites` from art/anims/*.json. Do not edit by hand.',
    '// Each frame: [ms, palette (0xRRGGBB), 256 pixels as base-36 palette indices, row-major].',
    '',
    'export type PackedFrame = readonly [ms: number, palette: readonly number[], pixels: string];',
    '',
    'export const SPRITES: Readonly<Record<string, readonly PackedFrame[]>> = {',
  ];
  for (const state of STATES) {
    const file = JSON.parse(readFileSync(join(dir, `${state}.json`), 'utf8')) as AnimFile;
    lines.push(`  '${state}': [`);
    file.frames.forEach((f, i) => {
      if (f.idx.length !== PIXELS) throw new Error(`${state} frame ${i}: expected ${PIXELS} pixels`);
      if (f.palette.length > 36) throw new Error(`${state} frame ${i}: more than 36 colours`);
      const pal = f.palette.map((hex) => '0x' + hex.replace('#', '').toLowerCase()).join(', ');
      const px = f.idx.map((n) => n.toString(36)).join('');
      lines.push(`    [${f.ms}, [${pal}], '${px}'],`);
    });
    lines.push('  ],');
  }
  lines.push('};', '');
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(MOD_SPRITES_PATH, modSpritesSource());
  console.log(`wrote ${MOD_SPRITES_PATH}`);
}
